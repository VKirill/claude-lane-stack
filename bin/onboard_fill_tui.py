#!/usr/bin/env python3
"""Split-pane live view for project-onboard fill.

Left  — phase + pack checklist (green when filled).
Right — scrolling codex/cursor log.

Usage:
  onboard_fill_tui.py --repo DIR --art DIR --log FILE [--pid PID] [--has-ui 0|1] [--has-deploy 0|1]
  Keys: ↑↓/PgUp/PgDn/wheel scroll log · End follow live · q detach (writer keeps running)
"""
from __future__ import annotations

import argparse
import os
import re
import sys
import time
from pathlib import Path
from shutil import get_terminal_size as shutil_get_terminal_size

# Case-sensitive on ERROR/FAILED so code identifiers like compensationError stay quiet.
_ERR_LINE = re.compile(
    r"(Traceback \(most recent call last\)|"
    r"\bERROR\b|"
    r"verification failed|"
    r"VALIDATION gate failed|"
    r"\bFAILED\b|"
    r"exited 1\b|"
    r"exit=1\b|"
    r"^Exception:|"
    r"JSONDecodeError:|"
    r"TypeError:|"
    r"PermissionError:)"
)


PHASES = [
    ("phase1-layout.md", "Phase 1  layout + TAXONOMY"),
    ("phase2-maps.md", "Phase 2  MODULE / API / TEST"),
    ("phase3-flows.md", "Phase 3  FLOWS"),
    ("phase4-passport.md", "Phase 4  passport + DESIGN/RUNBOOK"),
    ("phase4b-app-packs.md", "Phase 4b per-app CLAUDE+docs"),
    ("phase5-critique.md", "Phase 5  validation"),
    ("report.md", "Report"),
]


def _pack_items(repo: Path, has_ui: bool, has_deploy: bool) -> list[tuple[Path, str]]:
    items = [
        (repo / "docs/llm/TAXONOMY.yaml", "TAXONOMY.yaml"),
        (repo / "docs/llm/MODULE_MAP.yaml", "MODULE_MAP.yaml"),
        (repo / "docs/llm/API_SURFACE.yaml", "API_SURFACE.yaml"),
        (repo / "docs/llm/TEST_INDEX.yaml", "TEST_INDEX.yaml"),
        (repo / "docs/llm/FLOWS.md", "FLOWS.md"),
        (repo / "docs/llm/INDEX.md", "INDEX.md"),
        (repo / "docs/ARCHITECTURE.md", "ARCHITECTURE.md"),
        (repo / "CLAUDE.md", "CLAUDE.md"),
        (repo / "llms.txt", "llms.txt"),
    ]
    if has_ui:
        items.append((repo / "docs/DESIGN.md", "DESIGN.md"))
    if has_deploy:
        items.append((repo / "docs/RUNBOOK.md", "RUNBOOK.md"))
    return items


def _filled(path: Path) -> bool:
    if not path.is_file():
        return False
    try:
        text = path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return False
    if len(text.strip()) < 40:
        return False
    # Stubs left by seed
    if "REPLACE_ME" in text:
        return False
    if re.search(r"(?m)^modules:\s*\[\s*\]\s*$", text):
        return False
    if re.search(r"(?m)^surfaces:\s*\[\s*\]\s*$", text):
        return False
    if re.search(r"(?m)^tests:\s*\[\s*\]\s*$", text):
        return False
    if "one-line purpose for agents" in text:
        return False
    if "Generated by project-onboard seed" in text and path.name == "ARCHITECTURE.md":
        return False
    return True


def _alive(pid: int | None) -> bool:
    if not pid:
        return True
    try:
        os.kill(pid, 0)
        return True
    except OSError:
        return False


def _log_lines(path: Path, max_chars: int = 120, max_bytes: int = 512_000) -> list[str]:
    if not path.is_file():
        return ["(waiting for log…)"]
    try:
        data = path.read_bytes()
    except OSError:
        return ["(log unreadable)"]
    if len(data) > max_bytes:
        data = data[-max_bytes:]
    text = data.decode("utf-8", errors="replace")
    out = []
    for line in text.splitlines():
        s = line.replace("\t", " ")
        if len(s) > max_chars:
            s = s[: max_chars - 1] + "…"
        out.append(s)
    return out or ["(log empty)"]


def _slice_log(lines: list[str], max_lines: int, scroll_up: int) -> tuple[list[str], int]:
    """Return window ending `scroll_up` lines before EOF, and clamped scroll."""
    n = len(lines)
    if n <= max_lines:
        return lines, 0
    max_scroll = n - max_lines
    scroll = max(0, min(int(scroll_up), max_scroll))
    end = n - scroll
    start = end - max_lines
    return lines[start:end], scroll


def _is_err_line(line: str) -> bool:
    return bool(_ERR_LINE.search(line))


def run_tui(
    repo: Path,
    art: Path,
    log: Path,
    pid: int | None,
    has_ui: bool,
    has_deploy: bool,
    model: str,
) -> int:
    try:
        from prompt_toolkit.application import Application
        from prompt_toolkit.key_binding import KeyBindings
        from prompt_toolkit.layout import (
            FormattedTextControl,
            HSplit,
            Layout,
            VSplit,
            Window,
            WindowAlign,
        )
        from prompt_toolkit.mouse_events import MouseEventType
        from prompt_toolkit.styles import Style
    except ImportError:
        print("prompt_toolkit missing — plain tail:", log, file=sys.stderr)
        return _plain_follow(log, pid)

    pack = _pack_items(repo, has_ui, has_deploy)
    started = time.time()
    state = {"exit_code": 0, "done": False, "scroll": 0, "view_lines": 40}

    def left_text():
        elapsed = int(time.time() - started)
        mm, ss = divmod(elapsed, 60)
        alive = _alive(pid)
        header = [
            ("class:title", " ONBOARD FILL\n"),
            ("class:muted", f" {repo.name}  ·  {model or 'model?'}\n"),
            (
                "class:ok" if alive and not state["done"] else "class:muted",
                f" {'● running' if alive and not state['done'] else '○ finished'}"
                f"  {mm:02d}:{ss:02d}\n",
            ),
            ("class:muted", " ─────────────────────────\n"),
            ("class:section", " PHASES\n"),
        ]
        for name, label in PHASES:
            ok = _filled(art / name)
            mark = "✔" if ok else "·"
            cls = "class:ok" if ok else "class:dim"
            header.append((cls, f"  {mark} {label}\n"))
        header.append(("class:muted", " ─────────────────────────\n"))
        header.append(("class:section", " PACK\n"))
        done_n = 0
        for path, label in pack:
            ok = _filled(path)
            done_n += int(ok)
            mark = "✔" if ok else "·"
            cls = "class:ok" if ok else "class:dim"
            header.append((cls, f"  {mark} {label}\n"))
        header.append(("class:muted", " ─────────────────────────\n"))
        header.append(("class:muted", f" {done_n}/{len(pack)} pack\n"))
        header.append(("class:muted", " ↑↓/wheel scroll · End\n"))
        header.append(("class:muted", " q detach\n"))
        return [(style, text, _log_mouse) for style, text in header]

    def _log_mouse(mouse_event):
        # prompt_toolkit: SCROLL_UP = wheel away (content up / older lines)
        et = mouse_event.event_type
        step = 3
        if et == MouseEventType.SCROLL_UP:
            state["scroll"] = min(state["scroll"] + step, 50_000)
            return None
        if et == MouseEventType.SCROLL_DOWN:
            state["scroll"] = max(0, state["scroll"] - step)
            return None
        return NotImplemented

    def right_text():
        try:
            rows = max(8, shutil_get_terminal_size().lines - 4)
        except Exception:
            rows = max(8, state.get("view_lines", 40))
        state["view_lines"] = rows
        all_lines = _log_lines(log, max_chars=110)
        lines, clamped = _slice_log(all_lines, rows, state["scroll"])
        state["scroll"] = clamped
        follow = clamped == 0
        head = " LOG  (live)" if follow else f" LOG  (↑{clamped} from end)"
        parts = [
            ("class:loghead", head + "\n"),
            ("class:muted", " ─" * 40 + "\n"),
        ]
        for line in lines:
            if _is_err_line(line):
                parts.append(("class:err", line + "\n"))
            elif line.startswith("==>") or line.startswith("[onboard]") or "PHASE4B" in line:
                parts.append(("class:accent", line + "\n"))
            else:
                parts.append(("class:log", line + "\n"))
        # Attach wheel handler to every fragment (pt formatted-text mouse API).
        return [(style, text, _log_mouse) for style, text in parts]

    kb = KeyBindings()

    @kb.add("q")
    @kb.add("c-c")
    def _(event):
        event.app.exit(result=state["exit_code"])

    @kb.add("up")
    def _(event):
        state["scroll"] = min(state["scroll"] + 1, 50_000)

    @kb.add("down")
    def _(event):
        state["scroll"] = max(0, state["scroll"] - 1)

    @kb.add("pageup")
    def _(event):
        state["scroll"] = min(state["scroll"] + max(5, state["view_lines"] - 2), 50_000)

    @kb.add("pagedown")
    def _(event):
        state["scroll"] = max(0, state["scroll"] - max(5, state["view_lines"] - 2))

    @kb.add("end")
    def _(event):
        state["scroll"] = 0

    @kb.add("home")
    def _(event):
        # Jump far up in the buffered window (last ~512KiB), not absolute file start.
        state["scroll"] = 50_000

    style = Style.from_dict(
        {
            "title": "bold ansicyan",
            "section": "bold ansiwhite",
            "ok": "ansigreen bold",
            "dim": "ansibrightblack",
            "muted": "ansibrightblack",
            "accent": "ansiyellow",
            "err": "ansired bold",
            "log": "ansiwhite",
            "loghead": "bold ansicyan",
            "frame": "ansibrightblack",
        }
    )

    left = Window(
        content=FormattedTextControl(left_text),
        width=36,
        wrap_lines=False,
        style="class:frame",
    )
    right = Window(
        content=FormattedTextControl(right_text),
        wrap_lines=False,
        style="class:frame",
    )
    body = VSplit(
        [
            left,
            Window(width=1, char="│", style="class:muted"),
            right,
        ]
    )
    root = HSplit(
        [
            Window(
                height=1,
                content=FormattedTextControl(
                    lambda: [
                        (
                            "class:title",
                            " Lane Stack · Onboard ",
                        ),
                        (
                            "class:muted",
                            " │ ↑↓/wheel scroll · End=live · q=detach ",
                        ),
                    ]
                ),
                align=WindowAlign.LEFT,
            ),
            body,
        ]
    )

    app = Application(
        layout=Layout(root, focused_element=right),
        key_bindings=kb,
        style=style,
        full_screen=True,
        mouse_support=True,
        refresh_interval=0.35,
    )

    def _watch():
        # Mark done when writer dies; keep UI until user quits or auto-exit shortly after.
        while True:
            time.sleep(0.4)
            if pid and not _alive(pid):
                state["done"] = True
                # Auto-exit a few seconds after writer ends if report exists
                if _filled(art / "report.md"):
                    time.sleep(1.2)
                    app.exit(result=0)
                    return
                time.sleep(2.0)
                app.exit(result=0)
                return

    import threading

    threading.Thread(target=_watch, daemon=True).start()
    return int(app.run() or 0)


def _plain_follow(log: Path, pid: int | None) -> int:
    print(f"(plain) tail -f {log}", flush=True)
    pos = 0
    while True:
        if log.is_file():
            with log.open("rb") as f:
                f.seek(pos)
                chunk = f.read()
                if chunk:
                    sys.stdout.buffer.write(chunk)
                    sys.stdout.buffer.flush()
                    pos = f.tell()
        if pid and not _alive(pid):
            return 0
        time.sleep(0.25)


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Onboard fill split-pane TUI")
    p.add_argument("--repo", required=True, type=Path)
    p.add_argument("--art", required=True, type=Path)
    p.add_argument("--log", required=True, type=Path)
    p.add_argument("--pid", type=int, default=0)
    p.add_argument("--has-ui", type=int, default=0)
    p.add_argument("--has-deploy", type=int, default=0)
    p.add_argument("--model", default="")
    args = p.parse_args(argv)
    if not sys.stdout.isatty() or os.environ.get("ONBOARD_PLAIN"):
        return _plain_follow(args.log, args.pid or None)
    return run_tui(
        args.repo.resolve(),
        args.art.resolve(),
        args.log.resolve(),
        args.pid or None,
        bool(args.has_ui),
        bool(args.has_deploy),
        args.model,
    )


if __name__ == "__main__":
    raise SystemExit(main())
